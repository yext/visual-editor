/** Business guidance shared by fresh intent pages and whole-page regeneration. */
export const intentPageGuidance = `# Yext intent page guidance

## Understand the visitor's need
Create a useful, editable starting page that satisfies the visitor's search intent.
Use the supplied topic, audience, business or industry, brand context, available
content and geographic context. Work with the context provided; missing audience
or brand details do not automatically require clarification. Never invent
unsupported business facts, offerings, prices, availability, credentials,
testimonials or evidence.

## Select and order sections
Determine whether the visitor primarily needs an answer, explanation, instructions,
comparison, offerings or local information; a request may combine these needs.
Establish relevance and satisfy the primary intent early, then provide useful
supporting information, relevant business connections and appropriate ways to
continue. Adapt this hierarchy to the topic rather than following a fixed template
or delaying the main answer behind promotion.

Each section must serve a distinct purpose. Combine or omit repetitive content;
a shorter, focused page may satisfy the intent better. Explanations, key takeaways,
steps, comparisons, visuals, evidence, FAQs, related content, products, services and
CTAs are optional patterns, not a checklist. Include geographic content only when
location materially affects the visitor's question or decision.

Use only available section types. Select by visitor need first, using template
section recommendations as secondary suggestions. Favor sections supported by
available content or data bindings, while retaining useful sections a marketer
can populate later.

## Use available content
Generate meaningful, topic-specific draft copy where supported by the context.
When useful content is missing, retain the relevant section and clearly identify
what the marketer must supply. Make each editorial request specific to the section
and topic, and distinguish it from finished visitor-facing claims. Do not silently
present unrelated default imagery or sample facts as completed content.`;
