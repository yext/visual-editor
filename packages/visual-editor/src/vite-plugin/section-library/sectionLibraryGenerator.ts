const GENERATED_FILE_PREFIX =
  "/** THIS FILE IS GENERATED BY THE SECTION LIBRARY PLUGIN */";

const reservedLayoutIds = new Set(["main", "directory", "locator", "edit"]);

/** A visible Section Library section and its static config metadata. */
type Section = SectionConfig & {
  /** The source filename without its extension. */
  componentName: string;
  /** The relative source path for generated imports. */
  sourcePath: string;
};

/** A Section Library layout and its metadata. */
type Layout = SectionLibraryLayout;

/** The complete validated Section Library source. */
type SectionLibrary = {
  metadata: LibraryMetadata;
  sections: Section[];
  sharedComponents: SharedComponent[];
  sharedRootPageSetTypes: PageSetType[];
  layouts: Layout[];
};

/** Section Library files and metadata generated for a build. */
type GeneratedSectionLibrary = {
  generatedFiles: string[];
  manifestSource?: string;
  layouts: Layout[];
};

/**
 * Generates the temporary Pages source files and build metadata for a Section
 * Library. The files exist only while Vite runs. It returns no files when the
 * starter has no library metadata.
 *
 * 1. Read and validate the library, section, shared-registry, and layout source.
 * 2. Generate one Puck config, Pages render template, and editor template per layout.
 * 3. Generate current Platform aliases and return the Section Library artifact manifest.
 */
export const generateSectionLibraryFiles = (
  rootDir: string,
  sectionLibraryRevisionId?: string
): GeneratedSectionLibrary => {
  if (!sectionLibraryRevisionId?.trim()) {
    throw new Error(
      "Section Library builds require SECTION_LIBRARY_REVISION_ID"
    );
  }

  const library = readSectionLibrary(rootDir);
  if (!library) {
    return { generatedFiles: [], layouts: [] };
  }

  const generatedDirectory = path.join(rootDir, "src", "library", ".generated");
  const generatedFiles = library.layouts.flatMap((layout) => {
    const configPath = path.join(
      generatedDirectory,
      `libraryConfig-${layout.metadata.id}.tsx`
    );
    return writeGeneratedFile(
      configPath,
      buildConfigSource(
        rootDir,
        layout,
        library.sections,
        library.sharedComponents,
        library.sharedRootPageSetTypes
      )
    )
      ? [configPath]
      : [];
  });

  const layoutsByPageSetType = new Map(
    library.layouts.map((layout) => [layout.metadata.pageSetType, layout])
  );
  const entityLayout = layoutsByPageSetType.get("ENTITY")!;
  const directoryLayout = layoutsByPageSetType.get("DIRECTORY")!;
  const locatorLayout = layoutsByPageSetType.get("LOCATOR")!;
  const aliasPaths = [
    path.join(rootDir, "src", "templates", "main.tsx"),
    path.join(rootDir, "src", "templates", "directory.tsx"),
    path.join(rootDir, "src", "templates", "locator.tsx"),
    path.join(rootDir, "src", "templates", "edit.tsx"),
  ];
  const aliasSources = [
    buildRenderTemplateSource(entityLayout),
    buildRenderTemplateSource(directoryLayout),
    buildRenderTemplateSource(locatorLayout),
    buildEditorTemplateSource([
      ["main", entityLayout],
      [entityLayout.metadata.id, entityLayout],
      ["directory", directoryLayout],
      [directoryLayout.metadata.id, directoryLayout],
      ["locator", locatorLayout],
      [locatorLayout.metadata.id, locatorLayout],
    ]),
  ];
  generatedFiles.push(
    ...aliasPaths.filter((filePath, index) => {
      return writeGeneratedFile(filePath, aliasSources[index]);
    })
  );
  generatedFiles.push(
    ...library.layouts.flatMap((layout) => {
      const filePath = path.join(
        rootDir,
        "src",
        "templates",
        `edit-${layout.metadata.id}.tsx`
      );
      return writeGeneratedFile(
        filePath,
        buildEditorTemplateSource(
          [[layout.metadata.id, layout]],
          `edit/${layout.metadata.id}/${encodeURIComponent(sectionLibraryRevisionId)}`,
          `edit-${layout.metadata.id}`
        )
      )
        ? [filePath]
        : [];
    })
  );
  writeLegacyTemplateManifest(
    rootDir,
    entityLayout,
    directoryLayout,
    locatorLayout
  );

  return {
    generatedFiles,
    layouts: library.layouts,
    manifestSource: `${JSON.stringify(
      {
        schemaVersion: 1,
        library: library.metadata,
        layouts: library.layouts.map((layout) => ({
          ...layout.metadata,
          templateId:
            layout.metadata.pageSetType === "ENTITY"
              ? "main"
              : layout.metadata.pageSetType.toLowerCase(),
          editorPath: `edit/${layout.metadata.id}/${encodeURIComponent(sectionLibraryRevisionId)}`,
          defaultLayout: layout.defaultLayout,
        })),
      },
      null,
      2
    )}\n`,
  };
};

/** Reads and validates the Section Library source. */
const readSectionLibrary = (rootDir: string): SectionLibrary | undefined => {
  const libraryDirectory = path.join(rootDir, "src", "library");
  const libraryJsonPath = path.join(libraryDirectory, "library.json");
  if (!fs.existsSync(libraryJsonPath)) {
    return undefined;
  }

  const metadata = readLibraryMetadata(libraryJsonPath);
  const sections = readSections(rootDir, libraryDirectory);
  const sharedRegistry = readSharedComponentRegistry(
    path.join(libraryDirectory, "shared", "componentRegistry.ts")
  );
  const sharedComponents = sharedRegistry?.components ?? [];
  const sharedRootPageSetTypes = sharedRegistry?.rootPageSetTypes ?? [];
  const layouts = readLayouts(libraryDirectory);
  if (
    !sharedRegistry &&
    layouts.some((layout) => layout.metadata.pageSetType !== "ENTITY")
  ) {
    throw new Error(
      `Missing shared component registry at ${path.join(libraryDirectory, "shared", "componentRegistry.ts")}`
    );
  }
  validateComponentIds(sections, sharedComponents);
  for (const layout of layouts) {
    validateLayoutReferences(layout, sections, sharedComponents);
  }
  return {
    metadata,
    sections,
    sharedComponents,
    sharedRootPageSetTypes,
    layouts,
  };
};

export const cleanupGeneratedSectionLibraryFiles = (
  generatedFiles: string[]
): void => {
  for (const filePath of generatedFiles) {
    fs.removeSync(filePath);
    if (filePath.endsWith(".tsx")) {
      fs.removeSync(filePath.replace(/\.tsx$/, ".client.tsx"));
    }
  }
};

const readLibraryMetadata = (filePath: string): LibraryMetadata => {
  const value = readJson(filePath, "library metadata");
  if (value.schemaVersion !== 1) {
    throw new Error(`${filePath} must set schemaVersion to 1`);
  }
  return {
    schemaVersion: 1,
    id: requireString(value.id, filePath, "id"),
    displayName: requireString(value.displayName, filePath, "displayName"),
    description: requireString(value.description, filePath, "description"),
  };
};

const readSections = (rootDir: string, libraryDirectory: string): Section[] => {
  const sectionsDirectory = path.join(libraryDirectory, "sections");
  if (!fs.existsSync(sectionsDirectory)) {
    return [];
  }

  return fs
    .readdirSync(sectionsDirectory, { withFileTypes: true })
    .filter((entry) => entry.name !== ".gitkeep")
    .sort((left, right) => left.name.localeCompare(right.name))
    .map((entry) => {
      const sourcePath = path.join(sectionsDirectory, entry.name);
      if (entry.isDirectory()) {
        throw new Error(`Section directories are not supported: ${sourcePath}`);
      }
      const extension = path.extname(entry.name);
      if (!entry.isFile() || ![".tsx", ".jsx"].includes(extension)) {
        throw new Error(`Sections must be .tsx or .jsx files: ${sourcePath}`);
      }

      const componentName = path.basename(entry.name, extension);
      if (!isSafeId(componentName)) {
        throw new Error(
          `Section component name is not valid: ${componentName}`
        );
      }
      const section: Section = {
        ...extractSectionConfigFrontmatter(sourcePath, componentName),
        componentName,
        sourcePath: path.relative(rootDir, sourcePath),
      };
      if (!isSafeId(section.id)) {
        throw new Error(`${sourcePath} config must define a valid id`);
      }
      return section;
    });
};

const readLayouts = (libraryDirectory: string): Layout[] => {
  const layoutsDirectory = path.join(libraryDirectory, "layouts");
  if (!fs.existsSync(layoutsDirectory)) {
    throw new Error(`Missing layouts directory at ${layoutsDirectory}`);
  }
  const layouts = fs
    .readdirSync(layoutsDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => readLayout(path.join(layoutsDirectory, entry.name)));
  if (layouts.length !== 3) {
    throw new Error(
      "Section Library build mode requires one ENTITY, one DIRECTORY, and one LOCATOR layout"
    );
  }
  const pageSetTypes = new Set(
    layouts.map((layout) => layout.metadata.pageSetType)
  );
  if (
    pageSetTypes.size !== 3 ||
    !["ENTITY", "DIRECTORY", "LOCATOR"].every((type) =>
      pageSetTypes.has(type as PageSetType)
    )
  ) {
    throw new Error(
      "Section Library build mode requires one ENTITY, one DIRECTORY, and one LOCATOR layout"
    );
  }
  return layouts;
};

const readLayout = (layoutDirectory: string): Layout => {
  const metadataPath = path.join(layoutDirectory, "metadata.json");
  const metadataValue = readJson(metadataPath, "layout metadata");
  const pageSetType = metadataValue.pageSetType;
  let metadata: LayoutMetadata;
  if (pageSetType === "ENTITY") {
    const vertical = getOptionalStringListProperty(
      metadataValue,
      "vertical",
      verticals,
      metadataPath
    );
    const purpose = getOptionalStringListProperty(
      metadataValue,
      "purpose",
      purposes,
      metadataPath
    );
    metadata = {
      id: requireString(metadataValue.id, metadataPath, "id"),
      displayName: requireString(
        metadataValue.displayName,
        metadataPath,
        "displayName"
      ),
      previewImageUrl: requireString(
        metadataValue.previewImageUrl,
        metadataPath,
        "previewImageUrl"
      ),
      ...(vertical === undefined ? {} : { vertical }),
      ...(purpose === undefined ? {} : { purpose }),
      pageSetType,
    };
  } else if (pageSetType === "DIRECTORY" || pageSetType === "LOCATOR") {
    metadata = {
      id: requireString(metadataValue.id, metadataPath, "id"),
      displayName: requireString(
        metadataValue.displayName,
        metadataPath,
        "displayName"
      ),
      pageSetType,
    };
  } else {
    throw new Error(`${metadataPath} must set a supported pageSetType`);
  }
  if (!isSafeId(metadata.id)) {
    throw new Error(`Layout ID is not valid: ${metadata.id}`);
  }
  if (reservedLayoutIds.has(metadata.id)) {
    throw new Error(
      `${metadataPath} cannot use ${metadata.id} because it is reserved for a generated template`
    );
  }
  return {
    metadata,
    defaultLayout: readJson(
      path.join(layoutDirectory, "defaultLayout.json"),
      `default layout for ${metadata.id}`
    ),
  };
};

const validateComponentIds = (
  sections: Section[],
  sharedComponents: SharedComponent[]
): void => {
  const componentIds = new Set<string>();
  for (const [componentTypeName, components] of [
    ["Section", sections],
    ["Component", sharedComponents],
  ] as const) {
    for (const component of components) {
      if (!isSafeId(component.id)) {
        throw new Error(
          `${componentTypeName} ID is not valid: ${component.id}`
        );
      }
      if (componentIds.has(component.id)) {
        throw new Error(
          `${componentTypeName} ID is not unique: ${component.id}`
        );
      }
      componentIds.add(component.id);
    }
  }
};

const validateLayoutReferences = (
  layout: Layout,
  sections: Section[],
  sharedComponents: SharedComponent[]
): void => {
  const componentIds = new Set(
    [...sections, ...sharedComponents]
      .filter((component) =>
        component.pageSetTypes.includes(layout.metadata.pageSetType)
      )
      .map((component) => component.id)
  );
  const instanceIds = new Set<string>();
  for (const component of collectLayoutComponents(layout.defaultLayout)) {
    const instanceId = component.props.id;
    if (typeof instanceId !== "string" || !instanceId) {
      throw new Error(
        `Layout ${layout.metadata.id} component ${component.type} must define an ID`
      );
    }
    if (instanceIds.has(instanceId)) {
      throw new Error(
        `Layout ${layout.metadata.id} component ID is not unique: ${instanceId}`
      );
    }
    instanceIds.add(instanceId);
    if (component.type !== "MainContent" && !componentIds.has(component.type)) {
      throw new Error(
        `Layout ${layout.metadata.id} references missing or incompatible section ${component.type}`
      );
    }
  }
};

const collectLayoutComponents = (
  value: unknown
): { type: string; props: Record<string, unknown> }[] => {
  if (!value || typeof value !== "object") {
    return [];
  }
  const layout = value as Record<string, unknown>;
  return [
    ...collectComponentList(layout.content),
    ...Object.values(layout.zones ?? {}).flatMap(collectComponentList),
  ];
};

const collectComponentList = (
  value: unknown
): { type: string; props: Record<string, unknown> }[] => {
  if (!Array.isArray(value)) {
    return [];
  }
  return value.flatMap((value) => {
    if (!value || typeof value !== "object") {
      return [];
    }
    const component = value as Record<string, unknown>;
    if (typeof component.type !== "string" || !component.props) {
      return [];
    }
    const props = component.props as Record<string, unknown>;
    const slots =
      props.slots && typeof props.slots === "object"
        ? Object.values(props.slots).flatMap(collectComponentList)
        : [];
    const mainContent =
      component.type === "MainContent"
        ? collectComponentList(props.content)
        : [];
    return [{ type: component.type, props }, ...slots, ...mainContent];
  });
};

/**
 * Writes the temporary Platform compatibility entries. Remove these entries
 * when Platform reads section-library-manifest.json for page set creation.
 */
const writeLegacyTemplateManifest = (
  rootDir: string,
  entityLayout: Layout,
  directoryLayout: Layout,
  locatorLayout: Layout
): void => {
  const manifestPath = path.join(rootDir, ".template-manifest.json");
  const source = JSON.stringify(
    {
      templates: [
        {
          name: "main",
          description:
            "Use this template to generate pages for each of your Locations.",
          exampleSiteUrl: "",
          layoutRequired: true,
          defaultLayoutData: JSON.stringify(entityLayout.defaultLayout),
        },
        {
          name: "directory",
          description:
            "Use this template to generate pages for each of your Directory entities.",
          exampleSiteUrl: "",
          layoutRequired: true,
          defaultLayoutData: JSON.stringify(directoryLayout.defaultLayout),
        },
        {
          name: "locator",
          description: "Use this template to generate pages for your Locators.",
          exampleSiteUrl: "",
          layoutRequired: true,
          defaultLayoutData: JSON.stringify(locatorLayout.defaultLayout),
        },
      ],
    },
    null,
    2
  );
  if (
    !fs.existsSync(manifestPath) ||
    fs.readFileSync(manifestPath, "utf8") !== source
  ) {
    fs.writeFileSync(manifestPath, source);
  }
};

const buildConfigSource = (
  rootDir: string,
  layout: Layout,
  sections: Section[],
  sharedComponents: SharedComponent[],
  sharedRootPageSetTypes: PageSetType[]
): string => {
  const layoutId = layout.metadata.id;
  const generatedPath = path.join(
    rootDir,
    "src",
    "library",
    ".generated",
    `libraryConfig-${layoutId}.tsx`
  );
  const supportedSections = sections.filter((section) => {
    return section.pageSetTypes.includes(layout.metadata.pageSetType);
  });
  const imports = supportedSections.map((section, index) => {
    const importPath = path
      .relative(
        path.dirname(generatedPath),
        path.join(rootDir, section.sourcePath)
      )
      .replace(/\.(tsx|jsx)$/, "")
      .split(path.sep)
      .join("/");
    const specifier = importPath.startsWith(".")
      ? importPath
      : `./${importPath}`;
    return `import { ${section.componentName} as Section${index}, config as sectionConfig${index} } from ${JSON.stringify(specifier)};`;
  });
  const entries = supportedSections.map((section, index) => {
    return `  { id: ${JSON.stringify(section.id)}, component: Section${index}, config: sectionConfig${index} },`;
  });
  const hasSharedComponentRegistry =
    sharedComponents.some((component) => {
      return component.pageSetTypes.includes(layout.metadata.pageSetType);
    }) || sharedRootPageSetTypes.includes(layout.metadata.pageSetType);
  return sectionLibraryConfigTemplate
    .replace("/* SECTION_LIBRARY_GENERATED_FILE */", GENERATED_FILE_PREFIX)
    .replace("/* SECTION_LIBRARY_IMPORTS */", imports.join("\n"))
    .replace("/* SECTION_LIBRARY_ENTRIES */", entries.join("\n"))
    .replace(
      "/* SECTION_LIBRARY_SHARED_COMPONENT_REGISTRY */",
      hasSharedComponentRegistry
        ? 'import { sharedComponentConfigs, sharedComponentMetadata, sharedRootAllowedComponentIds, sharedRootConfigs } from "../shared/componentRegistry";'
        : 'const sharedComponentMetadata: { id: string; pageSetTypes: string[] }[] = [];\nconst sharedComponentConfigs: Config["components"] = {};\nconst sharedRootAllowedComponentIds: Partial<Record<string, string[]>> = {};\nconst sharedRootConfigs: Partial<Record<string, NonNullable<Config["root"]>>> = {};'
    )
    .replace(
      "__SECTION_LIBRARY_PAGE_SET_TYPE__",
      JSON.stringify(layout.metadata.pageSetType)
    )
    .replace(
      "__SECTION_LIBRARY_HAS_SHARED_COMPONENT_REGISTRY__",
      hasSharedComponentRegistry ? "true" : "false"
    );
};

const buildRenderTemplateSource = (layout: Layout): string => {
  const configPath = `../library/.generated/libraryConfig-${layout.metadata.id}`;
  const mapboxImport =
    layout.metadata.pageSetType === "LOCATOR"
      ? 'import mapboxPackageJson from "mapbox-gl/package.json";'
      : "";
  const mapboxAssets =
    layout.metadata.pageSetType === "LOCATOR"
      ? `<><script id="mapbox-script" src={\`https://api.mapbox.com/mapbox-gl-js/v\${mapboxPackageJson.version}/mapbox-gl.js\`} /><link id="mapbox-stylesheet" rel="stylesheet" href={\`https://api.mapbox.com/mapbox-gl-js/v\${mapboxPackageJson.version}/mapbox-gl.css\`} /></>`
      : "";
  return sectionLibraryRenderTemplate
    .replace("/* SECTION_LIBRARY_GENERATED_FILE */", GENERATED_FILE_PREFIX)
    .replace(
      '"__SECTION_LIBRARY_LAYOUT_ID__"',
      JSON.stringify(layout.metadata.id)
    )
    .replace('"__SECTION_LIBRARY_CONFIG_PATH__"', JSON.stringify(configPath))
    .replace("/* SECTION_LIBRARY_MAPBOX_IMPORT */", mapboxImport)
    .replace("{/* SECTION_LIBRARY_MAPBOX_ASSETS */}", mapboxAssets);
};

const buildEditorTemplateSource = (
  entries: [string, Layout][],
  editorPath: string = "edit",
  editorName: string = "edit"
): string => {
  const registry = entries
    .map(([name, entry]) => {
      const configPath = `../library/.generated/libraryConfig-${entry.metadata.id}`;
      return `  ${JSON.stringify(name)}: () => import(${JSON.stringify(configPath)}).then(({ sectionLibraryConfig }) => sectionLibraryConfig),`;
    })
    .join("\n");
  return sectionLibraryEditorTemplate
    .replace("/* SECTION_LIBRARY_GENERATED_FILE */", GENERATED_FILE_PREFIX)
    .replace("/* SECTION_LIBRARY_CONFIG_IMPORTS */", "")
    .replace("/* SECTION_LIBRARY_COMPONENT_REGISTRY */", registry)
    .replace('"__SECTION_LIBRARY_EDITOR_PATH__"', JSON.stringify(editorPath))
    .replace('"__SECTION_LIBRARY_EDITOR_NAME__"', JSON.stringify(editorName));
};

const writeGeneratedFile = (filePath: string, source: string): boolean => {
  fs.ensureDirSync(path.dirname(filePath));
  if (fs.existsSync(filePath)) {
    const existingSource = fs.readFileSync(filePath, "utf8");
    if (!existingSource.startsWith(GENERATED_FILE_PREFIX)) {
      return false;
    }
    if (existingSource === source) {
      return true;
    }
  }
  fs.writeFileSync(filePath, source);
  return true;
};

const readJson = (
  filePath: string,
  description: string
): Record<string, unknown> => {
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing ${description} at ${filePath}`);
  }
  try {
    const value: unknown = JSON.parse(fs.readFileSync(filePath, "utf8"));
    if (!value || typeof value !== "object" || Array.isArray(value)) {
      throw new Error("must be a JSON object");
    }
    return value as Record<string, unknown>;
  } catch (error) {
    throw new Error(
      `Could not parse ${description} at ${filePath}: ${error instanceof Error ? error.message : String(error)}`
    );
  }
};

const requireString = (
  value: unknown,
  filePath: string,
  field: string
): string => {
  if (typeof value !== "string") {
    throw new Error(`${filePath} must define a string ${field}`);
  }
  return value;
};

const getOptionalStringListProperty = <T extends string>(
  metadata: Record<string, unknown>,
  name: string,
  allowedValues: readonly T[],
  filePath: string
): T[] | undefined => {
  const value = metadata[name];
  if (value === undefined) {
    return;
  }
  if (
    !Array.isArray(value) ||
    value.some(
      (item) => typeof item !== "string" || !allowedValues.includes(item as T)
    )
  ) {
    throw new Error(
      `${filePath} must define ${name} as a list of supported values`
    );
  }
  return value as T[];
};

/** Returns whether an identifier is safe for generated filenames and imports. */
const isSafeId = (value: string): boolean => /^[A-Za-z0-9_-]+$/.test(value);
