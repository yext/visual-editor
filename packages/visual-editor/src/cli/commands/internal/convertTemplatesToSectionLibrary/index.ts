import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import packageJson from "../../../../../package.json" with { type: "json" };
import { prepareBaseLibrary, readBaseLibrary } from "./baseLibrary.ts";
import { buildConversion } from "./conversion.ts";
import { readLegacyTemplates } from "./legacyTemplates.ts";
import { detectPackageManager } from "./packageManager.ts";
import { formatJson, isRecord, readJson } from "./shared.ts";
import { convertStreamConfig } from "./streamConfig.ts";
import type { Conversion, JsonRecord } from "./types.ts";
import { deleteLegacyTemplates, replaceLibrary } from "./writeLibrary.ts";

type ConvertOptions = {
  apply: boolean;
  deleteSource: boolean;
  targetDirectory: string;
  write?: (message: string) => void;
  installDependencies?: (manager: "npm" | "pnpm", directory: string) => void;
};

/**
 * Converts all legacy registry templates into one Section Library.
 *
 * 1. Export missing Directory and Locator source, then validate the base
 *    library and every legacy template.
 * 2. Build one Entity layout per template and one section per component ID.
 * 3. Validate project configuration, generated files, and dependencies before writing.
 * 4. Install matching dependencies and replace the library only after the staged copy is complete.
 * 5. Remove stale source after the converted library is in place.
 */
export const convertTemplatesToSectionLibrary = ({
  apply,
  deleteSource,
  targetDirectory,
  write = console.log,
  installDependencies,
}: ConvertOptions): void => {
  const rootDirectory = path.resolve(targetDirectory);
  const libraryDirectory = path.join(rootDirectory, "src", "library");
  const templates = readLegacyTemplates(rootDirectory);
  const preparedBaseLibrary = prepareBaseLibrary(rootDirectory);
  try {
    const baseLibrary = readBaseLibrary(preparedBaseLibrary.directory);
    const conversion = buildConversion(templates, baseLibrary);
    const streamConfigPath = path.join(rootDirectory, "stream.config.ts");
    const streamConfig = fs.existsSync(streamConfigPath)
      ? convertStreamConfig(
          fs.readFileSync(streamConfigPath, "utf8"),
          streamConfigPath,
          conversion
        )
      : undefined;
    const generatedTemplates = [
      "main.tsx",
      "directory.tsx",
      "locator.tsx",
      "edit.tsx",
    ]
      .map((name) => path.join(rootDirectory, "src", "templates", name))
      .filter((filePath) => fs.existsSync(filePath));
    if (deleteSource) {
      for (const filePath of generatedTemplates) {
        if (
          !fs
            .readFileSync(filePath, "utf8")
            .startsWith(
              "/** THIS FILE IS AUTOGENERATED AND SHOULD NOT BE EDITED */"
            )
        ) {
          throw new Error(
            `Refusing to remove template without the expected generated-file header: ${filePath}`
          );
        }
      }
    }
    const packagePath = path.join(rootDirectory, "package.json");
    const targetPackage = readJson(packagePath, "target package manifest");
    if (!isRecord(targetPackage)) {
      throw new Error(
        `Target package manifest must be a JSON object: ${packagePath}`
      );
    }
    const manager = detectPackageManager(rootDirectory, targetPackage);
    const lockPath = path.join(
      rootDirectory,
      manager === "npm" ? "package-lock.json" : "pnpm-lock.yaml"
    );
    const originalPackage = fs.readFileSync(packagePath, "utf8");
    const originalLock = fs.readFileSync(lockPath);
    const dependency = (
      name: string
    ): { bucket: JsonRecord; previous: string } => {
      const matches = [
        targetPackage.dependencies,
        targetPackage.devDependencies,
      ]
        .filter(isRecord)
        .filter((bucket) => Object.hasOwn(bucket, name));
      if (matches.length !== 1 || typeof matches[0][name] !== "string") {
        throw new Error(
          `${packagePath} must declare ${name} exactly once in dependencies or devDependencies`
        );
      }
      return { bucket: matches[0], previous: matches[0][name] };
    };
    const visualEditor = dependency("@yext/visual-editor");
    const puck = dependency("@puckeditor/core");
    const puckVersion = packageJson.dependencies["@puckeditor/core"];
    const manifestPath = path.join(rootDirectory, ".template-manifest.json");

    if (preparedBaseLibrary.temporaryDirectory) {
      write(
        "Directory and Locator source will be added to the converted library."
      );
    }
    writeReport({ apply, conversion, deleteSource, write });
    if (
      streamConfig !== undefined &&
      streamConfig !== fs.readFileSync(streamConfigPath, "utf8")
    ) {
      write(
        `  update ${streamConfigPath}: templates/templateId to layouts/layoutId`
      );
    }
    write(
      `  dependencies (${manager}): @yext/visual-editor ${visualEditor.previous} -> ${packageJson.version}; @puckeditor/core ${puck.previous} -> ${puckVersion}`
    );
    write(`  update ${lockPath}`);
    if (fs.existsSync(manifestPath)) {
      write(`  remove ${manifestPath}`);
    }
    if (deleteSource) {
      for (const filePath of generatedTemplates) write(`  remove ${filePath}`);
      for (const template of templates) write(`  remove ${template.directory}`);
    }
    if (!apply) {
      return;
    }

    visualEditor.bucket["@yext/visual-editor"] = packageJson.version;
    puck.bucket["@puckeditor/core"] = puckVersion;
    fs.writeFileSync(packagePath, formatJson(targetPackage));
    try {
      if (installDependencies) {
        installDependencies(manager, rootDirectory);
      } else {
        const result = spawnSync(manager, ["install", "--ignore-scripts"], {
          cwd: rootDirectory,
          stdio: "inherit",
        });
        if (result.error || result.status !== 0) {
          throw new Error(
            `${manager} install failed: ${result.error?.message ?? `exit status ${result.status}`}`
          );
        }
      }
    } catch (error) {
      fs.writeFileSync(packagePath, originalPackage);
      fs.writeFileSync(lockPath, originalLock);
      throw error;
    }
    replaceLibrary(libraryDirectory, preparedBaseLibrary.directory, conversion);
    if (streamConfig !== undefined)
      fs.writeFileSync(streamConfigPath, streamConfig);
    fs.rmSync(manifestPath, { force: true });
    if (deleteSource) {
      for (const filePath of generatedTemplates) {
        fs.rmSync(filePath);
        write(`Removed ${filePath}`);
      }
      deleteLegacyTemplates(templates, write);
    }
  } finally {
    if (preparedBaseLibrary.temporaryDirectory) {
      fs.rmSync(preparedBaseLibrary.temporaryDirectory, {
        recursive: true,
        force: true,
      });
    }
  }
};

const writeReport = ({
  apply,
  conversion,
  deleteSource,
  write,
}: {
  apply: boolean;
  conversion: Conversion;
  deleteSource: boolean;
  write: (message: string) => void;
}): void => {
  write(
    apply
      ? "Applying Section Library conversion:"
      : "Dry run: no files changed."
  );
  write(
    `  library: ${conversion.libraryMetadata.id} from ${conversion.templates[0].templateId}`
  );
  write(
    `  Entity layouts: ${conversion.templates.map((template) => template.templateId).join(", ")}`
  );
  write(
    `  shared sections: ${Array.from(conversion.components.keys()).join(", ")}`
  );
  for (const duplicate of conversion.duplicates) {
    write(
      `  duplicate section ${duplicate.componentId}: kept ${duplicate.keptTemplateId}, ignored ${duplicate.ignoredTemplateId}${duplicate.differs ? " (source differs)" : ""}`
    );
  }
  const headerFooterUsage = Object.values(conversion.templateHeaderFooter)
    .map((selection) => selection.component?.type ?? `no ${selection.kind}`)
    .join(" and ");
  write(
    `  Directory layout: ${conversion.directoryLayoutId} (using ${headerFooterUsage})`
  );
  write(
    `  Locator layout: ${conversion.locatorLayoutId} (using ${headerFooterUsage})`
  );
  write(
    deleteSource
      ? "  legacy source: remove after conversion"
      : "  legacy source: keep"
  );
  for (const selection of Object.values(conversion.templateHeaderFooter)) {
    if (selection.component) {
      continue;
    }
    if (selection.matches.length === 0) {
      write(
        `  Warning: ${selection.kind} will not be copied because ${conversion.templates[0].templateId} has no top-level type containing ${selection.kind}`
      );
    } else {
      write(
        `  Warning: ${selection.kind} will not be copied because ${conversion.templates[0].templateId} has multiple top-level matches: ${selection.matches.join(", ")}`
      );
    }
  }
};
